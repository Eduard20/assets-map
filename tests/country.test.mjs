test('off by default; dimension switch shows how results differ; evidence; close restores focus',()=>{
  const dom=new JSDOM('<button id="launch">Pilot</button>');const {document}=dom.window;const launcher=document.querySelector('button');let opens=0;
  const {dialog}=mountCountryPilot({document,launcher,beforeOpen:()=>opens++});
  dialog.showModal=()=>dialog.setAttribute('open','');dialog.close=()=>{dialog.removeAttribute('open');dialog.dispatchEvent(new dom.window.Event('close'));};
  assert.equal(dialog.open,false);assert.equal(dialog.querySelectorAll('article').length,0);
  launcher.click();assert.equal(opens,1);assert.equal(dialog.open,true);
  assert.equal(dialog.querySelector('h2').textContent,'Country exploration: Armenia · Pilot');
  const cards=()=>[...dialog.querySelectorAll('article h3')].map(h=>h.textContent),change=(id,v)=>{const s=dialog.querySelector(id);s.value=v;s.dispatchEvent(new dom.window.Event('change'));};
  assert.equal(cards().length,5);assert.ok(cards().includes('Corporación América Airports S.A.'));
  assert.match(dialog.textContent,/no country total and no "Armenian wealth" figure/);assert.match(dialog.textContent,/5 Armenian entities and 27 sourced facts/);
  change('#country-dimension','investorDomicile');assert.equal(dialog.querySelector('#country-value').value,'AM');
  assert.deepEqual(cards(),['The Armenian Apostolic Church, presented by Mother See of Holy Etchmiadzin → Converse Bank CJSC']);
  change('#country-value','non_resident');assert.equal(cards().length,2);assert.match(dialog.textContent,/country not stated/);
  change('#country-dimension','issuerDomicile');assert.equal(cards().length,4);assert.ok(!cards().includes('Corporación América Airports S.A.'));
  change('#country-dimension','reportingCurrency');assert.equal(dialog.querySelector('#country-value').value,'AMD');assert.deepEqual(cards(),['Ameriabank CJSC']);assert.match(dialog.textContent,/never "where"/);
  change('#country-dimension','listingLocation');assert.deepEqual(cards(),['ACBA BANK OJSC']);
  [...dialog.querySelectorAll('.country-presets button')].find(b=>b.textContent==='Operating location = Armenia').click();assert.equal(cards().length,5);
  assert.match(dialog.textContent,/Chain: "Advanced Global Investments" S\.a\.r\.I\. \(former "Blakery Assets" LTD\) → "Advanced Global Investments" LLC → Converse Bank CJSC\. Look-through share: not computed/);
  assert.match(dialog.textContent,/Natural person, excluded for privacy/);assert.match(dialog.textContent,/Percentage unknown/);
  assert.doesNotMatch(dialog.textContent,/Eurnekian|total of|sum of/i);
  assert.ok(dialog.querySelectorAll('a').length>=5);assert.ok([...dialog.querySelectorAll('a')].every(a=>a.rel==='noopener noreferrer'&&a.href.startsWith('https://')));
  dialog.querySelector('button').click();assert.equal(document.activeElement,launcher);
});
